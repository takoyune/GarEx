"""Format inventory script for GarEx.

Generates docs/10_FORMAT_TRACKER.md from the exported formats inventory (tools/formats_inventory.json).
"""

from __future__ import annotations

import json
from pathlib import Path


def generate_tracker() -> None:
    root = Path(__file__).resolve().parent.parent
    json_path = root / "tools" / "formats_inventory.json"
    tracker_path = root / "docs" / "10_FORMAT_TRACKER.md"

    if not json_path.exists():
        raise FileNotFoundError(f"Inventory JSON not found at {json_path}. Run tools/export_inventory.ps1 first.")

    with json_path.open("r", encoding="utf-8-sig") as f:
        formats = json.load(f)

    # Sort formats by kind then Tag
    formats.sort(key=lambda x: (x.get("Kind", ""), x.get("Tag", "")))

    lines = [
        "<!--",
        "FILE CONTRACT",
        "Purpose : Single source of truth for every format upstream GARbro supports and its status in garex.",
        "Status  : GENERATED by tools/format_inventory.py. Agent updates status as work progresses.",
        "Status values : none | bridge | in-progress | native-partial | native",
        "Columns : Format name | Kind (archive/image/audio/script) | Extension(s) | Upstream class | Can extract | Can convert | Can create | garex status | Notes",
        "Rule    : Never mark `native` without a passing differential test.",
        "-->",
        "",
        "# Format Tracker",
        "",
        "| Format | Kind | Ext | Upstream class | Extract | Convert | Create | garex status | Notes |",
        "|---|---|---|---|:---:|:---:|:---:|:---:|---|",
    ]

    archives_count = 0
    images_count = 0
    audio_count = 0
    scripts_count = 0
    can_create_count = 0

    for fmt in formats:
        tag = (fmt.get("Tag") or "").replace("|", "\\|")
        kind = fmt.get("Kind", "")
        if kind == "archive":
            archives_count += 1
        elif kind == "image":
            images_count += 1
        elif kind == "audio":
            audio_count += 1
        elif kind == "script":
            scripts_count += 1

        ext = (fmt.get("Extensions") or "").replace("|", "\\|")
        cls_name = fmt.get("ClassName", "")
        can_extract = "yes" if fmt.get("CanExtract") else "-"
        can_convert = "yes" if fmt.get("CanConvert") else "-"
        can_create = "yes" if fmt.get("CanCreate") else "-"
        if fmt.get("CanCreate"):
            can_create_count += 1

        status = "bridge"  # Since upstream is now verified and built, bridge can access all of them

        lines.append(
            f"| `{tag}` | {kind} | {ext} | `{cls_name}` | {can_extract} | {can_convert} | {can_create} | {status} | {fmt.get('Description', '').replace('|', '\\|')} |"
        )

    lines.extend([
        "",
        "## Summary",
        f"- **Total formats**: {len(formats)}",
        f"  - **Archives**: {archives_count}",
        f"  - **Images**: {images_count}",
        f"  - **Audio**: {audio_count}",
        f"  - **Scripts**: {scripts_count}",
        f"  - **Supports packing/creation**: {can_create_count}",
        "- **garex status distribution**:",
        f"  - `bridge`: {len(formats)} (via compiled GARbro assemblies)",
        "  - `native-partial`: 0",
        "  - `native`: 0",
        "",
    ])

    tracker_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Successfully generated {tracker_path} with {len(formats)} formats.")


if __name__ == "__main__":
    generate_tracker()
